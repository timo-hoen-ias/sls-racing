// Measures the advance widths of the sign font (public/fonts/barlow-semi-condensed-500.woff2) in headless
// Chromium and prints src/world/signFont.ts. Layout in the pipeline and in the game uses the same table.
//   node tools/fonts/measure-sign-font.mjs > src/world/signFont.ts
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const { chromium } = createRequire(import.meta.url)('playwright');

const CHARS = ' !"&\'()+,-./0123456789:;?ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyzÄÖÜäöüßéèàáâçëïôûÉ';
const font = readFileSync(new URL('../../public/fonts/barlow-semi-condensed-500.woff2', import.meta.url)).toString('base64');
const browser = await chromium.launch();
const page = await browser.newPage();
const res = await page.evaluate(async ([b64, chars]) => {
  const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  const f = new FontFace('SignFont', bytes.buffer);
  await f.load();
  document.fonts.add(f);
  const ctx = document.createElement('canvas').getContext('2d');
  ctx.font = '1000px SignFont';
  const adv = {};
  for (const c of chars) adv[c] = Math.round(ctx.measureText(c).width);
  const m = ctx.measureText('H');
  const x = ctx.measureText('x');
  const d = ctx.measureText('g');
  return { adv, cap: Math.round(m.actualBoundingBoxAscent), xh: Math.round(x.actualBoundingBoxAscent), desc: Math.round(d.actualBoundingBoxDescent) };
}, [font, CHARS]);
await browser.close();
console.log(`// Generated by tools/fonts/measure-sign-font.mjs from public/fonts/barlow-semi-condensed-500.woff2 (OFL 1.1).
// Advance widths in 1/1000 em; CAP, X_HEIGHT and DESCENT also per 1000 em.
export const SIGN_FONT_ADVANCE: Record<string, number> = ${JSON.stringify(res.adv)};
export const SIGN_FONT_CAP = ${res.cap};
export const SIGN_FONT_X_HEIGHT = ${res.xh};
export const SIGN_FONT_DESCENT = ${res.desc};`);
