// Writes unreal/SlsRacing/Shaders/SlsAtlases.ush: the constants the Unreal surface shaders (SlsPbr.ush) share with
// the web game: atlas grids, metres per repeat, albedo gains and mean colours (as pbrTextures.ts computes them from
// public/textures/pbr/manifest.json), the ground channel palette (coverKinds.ts) and the Feldweg rut geometry
// (roadSpec.ts). Run after changing any of those; CI runs it with --check.
//   node unreal/tools/gen-shaders.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import * as THREE from 'three';
import { ATLASES, BUILDING, cellIndex, GUTTER, NATURE, STREET } from '../../src/render/pbr/textureSets.ts';
import { SPLAT, SPLAT_AERIAL_REF, SPLAT_COLOUR } from '../../src/world/coverKinds.ts';
import { FIELD_WAY } from '../../src/world/roadSpec.ts';
import { PUDDLE_FROM, PUDDLE_SIZE } from '../../src/weather/puddles.ts';

const OUT = 'unreal/SlsRacing/Shaders/SlsAtlases.ush';
const manifest = JSON.parse(readFileSync('public/textures/pbr/manifest.json', 'utf8')) as { atlases: Record<string, { cells: { mean: number[] }[] }> };
const f = (v: number) => v.toFixed(5);
const v3 = (c: number[]) => `float3(${c.map(f).join(', ')})`;
const lin = (hex: string) => { const c = new THREE.Color(hex); return [c.r, c.g, c.b]; };
const linRef = (rgb: [number, number, number]) => { const c = new THREE.Color().setRGB(rgb[0] / 255, rgb[1] / 255, rgb[2] / 255, THREE.SRGBColorSpace); return [c.r, c.g, c.b]; };

const lines: string[] = [
  '// Generated by unreal/tools/gen-shaders.ts from src/render/pbr/textureSets.ts, public/textures/pbr/manifest.json,',
  '// src/world/coverKinds.ts, src/world/roadSpec.ts and src/weather/puddles.ts. Do not edit by hand.',
  '#pragma once',
  '',
  `#define SLS_GUTTER ${f(GUTTER)}`,
  `#define SLS_RUT ${f(FIELD_WAY.rut)}`,
  `#define SLS_RUT_HALF ${f(FIELD_WAY.rutHalf)}`,
  `#define SLS_PUDDLE_SIZE ${f(PUDDLE_SIZE)}`,
  `#define SLS_PUDDLE_FROM ${f(PUDDLE_FROM)}`,
];
for (const a of ATLASES) {
  const U = a.name.toUpperCase();
  const cells = manifest.atlases[a.name]?.cells ?? [];
  const gain = a.sets.map((s, i) => {
    const m = cells[i]?.mean ?? [0.5, 0.5, 0.5];
    const lum = 0.2126 * m[0] + 0.7152 * m[1] + 0.0722 * m[2];
    return s.albedo ? s.albedo / Math.max(lum, 1e-3) : 1;
  });
  lines.push('', `#define SLS_${U}_COLS ${a.cols}.0`, `#define SLS_${U}_ROWS ${a.rows}.0`);
  lines.push(`static const float SLS_${U}_METRES[${a.sets.length}] = { ${a.sets.map((s) => f(s.metres)).join(', ')} };`);
  lines.push(`static const float SLS_${U}_GAIN[${a.sets.length}] = { ${gain.map(f).join(', ')} };`);
  lines.push(`static const float3 SLS_${U}_MEAN[${a.sets.length}] = { ${a.sets.map((_, i) => v3((cells[i]?.mean ?? [0.5, 0.5, 0.5]).map((x) => x * gain[i]))).join(', ')} };`);
  const p = a.name[0].toUpperCase();
  for (const s of a.sets) lines.push(`#define SLS_${p}_${s.name.toUpperCase()} ${cellIndex(a, s.name)}`);
}
lines.push('');
lines.push(`static const float3 SLS_GROUND_PAL[8] = { ${SPLAT.map((c) => v3(lin(SPLAT_COLOUR[c]))).join(', ')} };`);
lines.push(`static const float3 SLS_GROUND_REF[8] = { ${SPLAT.map((c) => v3(linRef(SPLAT_AERIAL_REF[c]))).join(', ')} };`);
lines.push(`static const float3 SLS_GROUND_DBG[8] = { ${['#4caf50', '#a5d66b', '#c8b45a', '#1b5e20', '#8d5a2b', '#808080', '#d8c8a8', '#3050c0'].map((h) => v3(lin(h))).join(', ')} };`);
const groundCells = [cellIndex(NATURE, 'grass'), cellIndex(NATURE, 'meadow'), cellIndex(NATURE, 'patchy'), cellIndex(NATURE, 'forest'), cellIndex(NATURE, 'field'), cellIndex(STREET, 'asphalt_worn'), cellIndex(STREET, 'gravel'), cellIndex(NATURE, 'mud')];
lines.push(`// Atlas cell per channel: nature cells, except paved and gravel (channels 5, 6) from the street atlas.`);
lines.push(`static const float SLS_GROUND_CELL[8] = { ${groundCells.map((c) => `${c}.0`).join(', ')} };`);
lines.push(`static const float3 SLS_FIELD_EARTH = ${v3(lin('#8a7658'))};`);
lines.push(`static const float3 SLS_FIELD_MUD = ${v3(lin('#5a4a38'))};`);
lines.push(`static const float3 SLS_FIELD_GRASS = ${v3(lin(SPLAT_COLOUR.meadow))};`);
void BUILDING;
const text = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  let old = '';
  try { old = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (old !== text) {
    console.error(`${OUT} ist veraltet: node unreal/tools/gen-shaders.ts`);
    process.exit(1);
  }
  console.log(`${OUT} aktuell`);
} else {
  writeFileSync(OUT, text);
  console.log(`geschrieben: ${OUT}`);
}
